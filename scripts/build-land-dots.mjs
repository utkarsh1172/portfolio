// Generates an evenly spaced grid of points on land for the hero globe.
// Run once with `npm run land-dots`; the output is committed so the site
// ships no map library at runtime.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const STEP = 1.9; // degrees of latitude between rows
const pts = [];
for (let lat = -58; lat <= 78; lat += STEP) {
  const circ = Math.cos((lat * Math.PI) / 180);
  const lonStep = STEP / Math.max(circ, 0.2);
  for (let lon = -180; lon < 180; lon += lonStep) {
    if (geoContains(land, [lon, lat])) pts.push(Math.round(lat * 10), Math.round(lon * 10));
  }
}
const out = `// Generated by scripts/build-land-dots.mjs — do not edit by hand.
// Flat array of [lat*10, lon*10] pairs for points on land.
export const LAND_DOTS: readonly number[] = ${JSON.stringify(pts)};
`;
writeFileSync(new URL("../src/data/land-dots.ts", import.meta.url), out);
console.log(`${pts.length / 2} land points, ${(out.length / 1024).toFixed(1)} KB`);
